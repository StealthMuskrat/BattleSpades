"""Generate raw world fixtures and expected columns by executing the original loader."""
import hashlib,json,pathlib,random,struct,sys
ROOT=pathlib.Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT))
from aoslib import vxl
out=ROOT/'java/src/test/resources/golden/world';out.mkdir(exist_ok=True)
fixtures={
 'empty':bytes([0,240,239,0]),
 'surface':bytes([0,200,200,0])+struct.pack('<I',0xff123456),
 'cave':bytes([4,180,180,0])+struct.pack('<III',0xff123456,0xffabcdef,0xff998877)+bytes([0,220,220,200])+struct.pack('<I',0xffaabbcc),
 'island':bytes([2,100,100,0])+struct.pack('<I',0xffee1234)+bytes([0,239,239,101])+struct.pack('<I',0xff556677),
 'small_grid':(bytes([0,239,239,0])+struct.pack('<I',0xff112233))*4,
 'classic_water':bytes([0,64,63,0])*(512*512),
}
rows=[];rng=random.Random(168)
for name,data in fixtures.items():
 p=out/(name+'.vxl');p.write_bytes(data)
 m=vxl.VXL(None,data,len(data));assert m.ready,name
 points=[(255,255,z) for z in range(240)]+[(256,256,z) for z in range(240)]
 points += [(rng.randrange(512),rng.randrange(512),rng.randrange(240)) for _ in range(64)]
 expected=[]
 for x,y,z in points: expected.append([x,y,z,bool(m.get_solid(x,y,z)),int(m.get_color(x,y,z))])
 columns=[]
 for x,y in [(0,0),(255,255),(256,256),(511,511)]: columns.append([x,y,m.serialize_columns([(x,y)])[8:].hex()])
 (out/(name+'.json')).write_text(json.dumps(dict(points=expected,columns=columns)))
 # TSV consumed by JUnit, generated by original APIs, not Java.
 for x,y,z,solid,color in expected: rows.append(f'{name}\t{x}\t{y}\t{z}\t{int(solid)}\t{color}')
 (out/(name+'.columns.tsv')).write_text('\n'.join(f'{x}\t{y}\t{data}' for x,y,data in columns)+'\n')
(out/'points.tsv').write_text('\n'.join(rows)+'\n')
print(len(fixtures),'VXL fixtures,',len(rows),'point oracle samples')
# Original KV6 loader accepts both layouts; fixtures carry palette trailers in standard only.
from aoslib import kv6
for legacy in [False,True]:
 data=b'Kvxl'+struct.pack('<II',2,2)
 if not legacy:data+=struct.pack('<I',8)
 data+=struct.pack('<fffI',1.0,-2.0,0.5,2)
 data+=struct.pack('<4BH2B',0x56,0x34,0x12,255,3,63,7)+struct.pack('<4BH2B',0xef,0xcd,0xab,128,7,31,5)
 data+=struct.pack('<2I',1,1)+struct.pack('<4H',1,0,0,1)
 if not legacy:data+=b'SPal'+bytes(range(32))
 name='legacy' if legacy else 'standard'
 (out/(name+'.kv6')).write_bytes(data)
print('2 KV6 binary fixtures')
